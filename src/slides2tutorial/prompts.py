"""Prompt templates for page explanations and rolling summaries."""

PAGE_PROMPT_TEMPLATE = """你是一位大学《计算机网络》课程老师。请根据我提供的这一页 PDF 截图，生成一份信息充分、解释清楚、适合学生复习的中文课堂笔记。

核心目标：
1. 解释本页真正承载的知识点，帮助学生复习和理解。
2. 接着之前的内容讲，保持概念、符号、术语连续；概念跳转时用 1-2 句自然过渡。
3. 优先保留定义、结构、因果关系、公式、例子、易错点，并把抽象概念讲到学生能直观理解。
4. 对封面页、目录页、过渡页，只提取必要信息，控制在 5-8 个要点内，不要扩写成完整章节导读。

严格禁止输出的内容：
- 不要写寒暄、课堂开场、欢迎语，例如“同学们好”“欢迎来到课堂”。
- 不要写包装句，例如“以下是本页的详细课堂笔记”“接下来我们进入”“本页幻灯片非常经典/重要”。
- 不要评价幻灯片，不要说“这页很经典”“考试重灾区”，除非截图中明确写了考试要求。
- 不要用评价性形容词包装内容，例如“经典”“权威”“重要”“宏观视角”；除非这些词是截图原文或专有名称的一部分。
- 对封面页中的作者、单位、参考来源只做客观列举，不添加教材评价或学习建议。
- 不要写“老师的话”“课前预告”“学习建议”“总结本页内容”这类额外栏目。
- 不要在回答里再写“第 X 页讲解”作为标题；外层 Markdown 已经会添加页码标题。
- 不要用“我们要想……首先……”这种泛泛导入。第一句话应直接进入本页知识点。

内容要求：
1. 请深入浅出、清晰易懂地解释这一页的内容，不要只是复述幻灯片文字。
2. 对过于抽象的概念，给出一个直观解释、生活类比或小例子；类比要短，服务于理解，不要喧宾夺主。
3. 如果本页从一个概念跳到另一个概念，请补一段短过渡说明“为什么要从 A 讲到 B”。
4. 如果本页包含公式、推导、协议字段、时延、带宽、吞吐量、概率、队列、窗口、序号等内容，请使用 Markdown + LaTeX 书写。
5. 行内公式可以用 `$...$`，重要公式或推导请使用 `$$...$$` 独立成块。
6. 不要使用图片占位符，不要说“如图所示”后就结束，要把图里的关键信息讲出来。
7. 如果幻灯片里有英文术语，请保留英文，并给出自然的中文解释。
8. 如果这一页和前面讲过的概念有关，用 1-2 句话点明联系，再讲本页内容；不要写长篇回顾。
9. 可以补充必要背景知识，但要紧贴本页，标成“补充：”；补充内容不要超过本页核心讲解。

输出格式要求：
- 使用 Markdown。
- 直接从本页核心小标题或第一条知识点开始。
- 使用清晰但简短的小标题。
- 可以使用项目符号、编号列表、表格。
- 重要公式必须使用 `$$...$$`。
- 输出应像一份学生可以直接复习的讲义笔记，而不是聊天回答。
- 不要输出与本页无关的泛泛介绍或对后续课程的预告。
- 不要编造截图中没有依据的细节；如果确实需要补充背景知识，请明确作为“补充：”。
- 默认篇幅适中展开：普通知识页控制在 700-1200 中文字左右；封面、目录、纯过渡页可以更短；信息密集页可以更长。

之前课程内容如下：
{previous_context}

请现在讲解当前这一页。
"""

SUMMARY_PROMPT_TEMPLATE = """你正在维护一份《计算机网络》课程的连续讲义上下文摘要。

请根据已有摘要和新完成的页面讲解，更新一份简洁但信息密度高的上下文摘要，供后续页面继续讲解时使用。

摘要必须保留：
1. 已经定义过的重要概念、术语、英文缩写和中文解释。
2. 已经出现过的关键公式，公式请使用 Markdown + LaTeX，并用 `$$...$$` 表示重要公式。
3. 前后页面之间的逻辑进展。
4. 老师后续讲解时需要沿用的符号、变量含义、例子或类比。

摘要要求：
- 用中文 Markdown 输出。
- 保持简洁，不要逐字复述。
- 不要丢失关键定义和公式。
- 不要加入新页面没有支持的新内容。
- 不要保留寒暄、课堂开场、页面评价、学习建议、课前预告、“以下是笔记”等无复用价值的话术。

已有摘要：
{old_summary}

新页面讲解：
{new_page_response}

请输出更新后的上下文摘要。
"""

EMPTY_CONTEXT = "（之前内容为空。这是课程讲解的第一页或断点前尚无可用上下文。）"


def build_page_prompt(previous_context: str) -> str:
    """Build the page prompt with an explicit empty-context marker."""

    return PAGE_PROMPT_TEMPLATE.format(
        previous_context=previous_context.strip() or EMPTY_CONTEXT
    )


def build_summary_prompt(old_summary: str, new_page_response: str) -> str:
    """Build the summary update prompt."""

    return SUMMARY_PROMPT_TEMPLATE.format(
        old_summary=old_summary.strip() or "（暂无已有摘要。）",
        new_page_response=new_page_response.strip(),
    )
